/**
 * Seeds a Supabase project with the Berkeley demo data.
 *
 *   npm run seed:sql   writes supabase/seed.sql (donation and disposal places).
 *                      The Supabase CLI runs it on `supabase db reset`.
 *   npm run seed       also creates demo neighbors and their listings in a
 *                      live project. Needs SUPABASE_URL and
 *                      SUPABASE_SERVICE_ROLE_KEY in the environment. Never put
 *                      the service role key in the app's .env.
 *
 * Safe to run more than once: places are upserted, and existing demo users
 * and listings are left alone.
 */
import { createClient } from '@supabase/supabase-js';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

import { buildSeed } from '../src/data/seed/listings';
import { seedUsers } from '../src/data/seed/people';
import { seedPlaces } from '../src/data/seed/places';

const q = (v: string | null) => (v === null ? 'null' : `'${v.replace(/'/g, "''")}'`);
const arr = (v: string[]) => `array[${v.map((x) => q(x)).join(', ')}]::text[]`;
const point = (lat: number, lng: number) =>
  `extensions.st_setsrid(extensions.st_makepoint(${lng}, ${lat}), 4326)::extensions.geography`;

function placesSql(): string {
  const rows = seedPlaces.map(
    (p) => `insert into public.disposal_locations
  (id, name, kind, tier, location, address, phone, url, hours, accepts, min_condition, refuses, takes_flags,
   pickup, pickup_note, dropoff, tax_receipt, why, note, cost_note, source, checked)
values
  (${q(p.id)}, ${q(p.name)}, ${q(p.kind)}, ${p.tier}, ${point(p.location.lat, p.location.lng)}, ${q(p.address)},
   ${q(p.phone)}, ${q(p.url)}, ${p.hours === null ? 'null' : `${q(JSON.stringify(p.hours))}::jsonb`},
   ${arr(p.accepts)}, ${q(p.minCondition)}, ${arr(p.refuses)}, ${arr(p.takesFlags)}, ${q(p.pickup)},
   ${q(p.pickupNote)}, ${p.dropoff}, ${p.taxReceipt}, ${q(p.why)}, ${q(p.note)}, ${q(p.costNote)},
   ${q(p.source)}, ${q(p.checked)})
on conflict (id) do update set
  name = excluded.name, kind = excluded.kind, tier = excluded.tier, location = excluded.location,
  address = excluded.address, phone = excluded.phone, url = excluded.url, hours = excluded.hours,
  accepts = excluded.accepts, min_condition = excluded.min_condition, refuses = excluded.refuses,
  takes_flags = excluded.takes_flags, pickup = excluded.pickup, pickup_note = excluded.pickup_note,
  dropoff = excluded.dropoff, tax_receipt = excluded.tax_receipt, why = excluded.why, note = excluded.note,
  cost_note = excluded.cost_note, source = excluded.source, checked = excluded.checked;`,
  );
  return `-- Generated by scripts/seed.ts from src/data/seed/places.ts. Edit that file, then run npm run seed:sql.\n\n${rows.join('\n\n')}\n`;
}

async function seedLive() {
  const url = process.env.SUPABASE_URL;
  const key = process.env.SUPABASE_SERVICE_ROLE_KEY;
  if (!url || !key) {
    console.log('SUPABASE_URL and SUPABASE_SERVICE_ROLE_KEY are not set, so only seed.sql was written.');
    return;
  }
  const admin = createClient(url, key, { auth: { persistSession: false } });

  const places = seedPlaces.map((p) => ({
    id: p.id,
    name: p.name,
    kind: p.kind,
    tier: p.tier,
    location: `SRID=4326;POINT(${p.location.lng} ${p.location.lat})`,
    address: p.address,
    phone: p.phone,
    url: p.url,
    hours: p.hours,
    accepts: p.accepts,
    min_condition: p.minCondition,
    refuses: p.refuses,
    takes_flags: p.takesFlags,
    pickup: p.pickup,
    pickup_note: p.pickupNote,
    dropoff: p.dropoff,
    tax_receipt: p.taxReceipt,
    why: p.why,
    note: p.note,
    cost_note: p.costNote,
    source: p.source,
    checked: p.checked,
  }));
  const placesRes = await admin.from('disposal_locations').upsert(places);
  if (placesRes.error) throw placesRes.error;
  console.log(`Places: ${places.length} upserted.`);

  // One auth user per demo neighbor. The seed's own ids are mapped to real auth ids.
  const idMap = new Map<string, string>();
  const existing = await admin.auth.admin.listUsers({ perPage: 1000 });
  if (existing.error) throw existing.error;
  for (const u of seedUsers) {
    const email = `${u.id.replace('u_', '')}@demo.curbside.test`;
    let authUser = existing.data.users.find((x) => x.email === email);
    if (!authUser) {
      const made = await admin.auth.admin.createUser({
        email,
        email_confirm: true,
        password: crypto.randomUUID(),
        user_metadata: { demo: true },
      });
      if (made.error) throw made.error;
      authUser = made.data.user;
    }
    idMap.set(u.id, authUser.id);
    const prof = await admin
      .from('profiles')
      .update({ name: u.name, neighborhood: u.neighborhood, verified: u.verified, rating: u.rating, handoffs: u.handoffs })
      .eq('id', authUser.id);
    if (prof.error) throw prof.error;
  }
  console.log(`Neighbors: ${idMap.size} ready.`);

  const { listings } = buildSeed(Date.now());
  let added = 0;
  for (const l of listings) {
    const owner = idMap.get(l.ownerId);
    if (!owner) continue;
    const dupe = await admin.from('listings').select('id').eq('owner_id', owner).eq('title', l.title).maybeSingle();
    if (dupe.data) continue;
    const ins = await admin
      .from('listings')
      .insert({
        owner_id: owner,
        title: l.title,
        category: l.category,
        subcategory: l.subcategory,
        color: l.color,
        material: l.material,
        condition: l.condition,
        dims: l.dims,
        brand: l.brand,
        description: l.description,
        tags: l.tags,
        pickup: l.pickup,
        weight_class: l.weightClass,
        price_usd: l.priceUsd,
        est_value_usd: l.estValueUsd,
        neighborhood: l.neighborhood,
        approx: `SRID=4326;POINT(${l.approx.lng} ${l.approx.lat})`,
        mode: l.mode,
        available_today: l.availableToday,
        created_at: new Date(l.createdAt).toISOString(),
      })
      .select('id')
      .single();
    if (ins.error) throw ins.error;
    const id = ins.data.id as string;
    // The trigger on listing_private re-blurs `approx` from this point.
    const priv = await admin.from('listing_private').insert({
      listing_id: id,
      address: l.address,
      exact: `SRID=4326;POINT(${l.approx.lng} ${l.approx.lat})`,
    });
    if (priv.error) throw priv.error;
    const photos = await admin
      .from('listing_photos')
      .insert(l.photos.map((url, position) => ({ listing_id: id, url, position, moderated: true })));
    if (photos.error) throw photos.error;
    added += 1;
  }
  console.log(`Listings: ${added} added, ${listings.length - added} already there.`);
}

const out = fileURLToPath(new URL('../supabase/seed.sql', import.meta.url));
writeFileSync(out, placesSql());
console.log(`Wrote ${out}`);
if (!process.argv.includes('--sql-only')) {
  seedLive().catch((e) => {
    console.error(e);
    process.exit(1);
  });
}
